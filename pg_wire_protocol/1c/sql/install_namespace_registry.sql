-- APP-10: private, database-local identities for exact native schema names.
-- Run once as database owner/administrator, with concurrent DDL stopped.
-- Supply the database and credentials to native isql, not in this file.
-- An existing PGWIRE_COMPAT is an error, never an upgrade or repair request.
SET BAIL ON;
SET AUTODDL OFF;

CREATE SCHEMA PGWIRE_COMPAT;

CREATE SEQUENCE PGWIRE_COMPAT.NAMESPACE_SEQ;
CREATE TABLE PGWIRE_COMPAT.NAMESPACE_IDS (
    NATIVE_NAME VARCHAR(63) CHARACTER SET SYSTEM.UTF8 COLLATE SYSTEM.UTF8
        NOT NULL PRIMARY KEY,
    NAMESPACE_ID BIGINT NOT NULL UNIQUE
        CHECK (NAMESPACE_ID BETWEEN 1 AND 4294967295)
);

-- Strip only metadata CHAR padding; preserve case and meaningful name bytes.
INSERT INTO PGWIRE_COMPAT.NAMESPACE_IDS (NATIVE_NAME, NAMESPACE_ID)
    SELECT TRIM(TRAILING FROM S.RDB$SCHEMA_NAME),
           NEXT VALUE FOR PGWIRE_COMPAT.NAMESPACE_SEQ
      FROM SYSTEM.RDB$SCHEMAS S;

-- DISTINCT makes this projection read-only even for a user with write grants.
CREATE VIEW PGWIRE_COMPAT.NAMESPACES (NATIVE_NAME, NAMESPACE_ID) AS
    SELECT DISTINCT NATIVE_NAME, NAMESPACE_ID
      FROM PGWIRE_COMPAT.NAMESPACE_IDS;
GRANT USAGE ON SCHEMA PGWIRE_COMPAT TO PUBLIC;
GRANT SELECT ON PGWIRE_COMPAT.NAMESPACES TO PUBLIC;

SET TERM ^;
CREATE TRIGGER PGWIRE_COMPAT.NAMESPACE_DDL
    ACTIVE AFTER ANY DDL STATEMENT
    SQL SECURITY DEFINER
AS
    DECLARE NAME_VALUE VARCHAR(63) CHARACTER SET SYSTEM.UTF8;
BEGIN
    IF (RDB$GET_CONTEXT('DDL_TRIGGER', 'OBJECT_TYPE') <> 'SCHEMA') THEN
        EXIT;

    NAME_VALUE = RDB$GET_CONTEXT('DDL_TRIGGER', 'OBJECT_NAME');
    IF (RDB$GET_CONTEXT('DDL_TRIGGER', 'EVENT_TYPE') = 'CREATE') THEN
        INSERT INTO PGWIRE_COMPAT.NAMESPACE_IDS (NATIVE_NAME, NAMESPACE_ID)
            VALUES (:NAME_VALUE, NEXT VALUE FOR PGWIRE_COMPAT.NAMESPACE_SEQ);
    ELSE IF (RDB$GET_CONTEXT('DDL_TRIGGER', 'EVENT_TYPE') = 'DROP') THEN
        DELETE FROM PGWIRE_COMPAT.NAMESPACE_IDS WHERE NATIVE_NAME = :NAME_VALUE;
    -- ALTER preserves identity. All changes use the original DDL transaction.
END^
SET TERM ;^

COMMIT;
