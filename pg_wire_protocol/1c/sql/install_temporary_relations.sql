-- APP-15: atomic upgrade of the accepted APP-14 SQL profile.
-- Run as owner/admin, without concurrent DDL. Existing objects are not repaired.
SET BAIL ON;
SET AUTODDL OFF;

CREATE EXCEPTION PGWIRE_COMPAT.TEMP_CONFIG_ERROR 'Invalid APP-15 temporary table configuration';

SET TERM ^;
EXECUTE BLOCK AS
    DECLARE SOURCE_TEXT VARCHAR(8191) CHARACTER SET SYSTEM.UTF8;
    DECLARE COUNTER_VALUE BIGINT;
BEGIN
    IF (EXISTS(SELECT 1 FROM SYSTEM.RDB$SCHEMAS
               WHERE RDB$SCHEMA_NAME = 'PGWIRE_TEMP' OR RDB$SCHEMA_NAME = 'pg_temp'
                  OR RDB$SCHEMA_NAME STARTING WITH 'pg_temp_')) THEN
        EXCEPTION PGWIRE_COMPAT.TEMP_CONFIG_ERROR;
    IF (NOT EXISTS(SELECT 1 FROM SYSTEM.RDB$TRIGGERS
                   WHERE RDB$SCHEMA_NAME='PGWIRE_COMPAT' AND RDB$TRIGGER_NAME='NAMESPACE_DDL'
                     AND RDB$TRIGGER_INACTIVE=0)) THEN
        EXCEPTION PGWIRE_COMPAT.TEMP_CONFIG_ERROR;
    IF (NOT EXISTS(SELECT 1 FROM SYSTEM.RDB$GENERATORS
                   WHERE RDB$SCHEMA_NAME='PGWIRE_COMPAT' AND RDB$GENERATOR_NAME='NAMESPACE_SEQ'
                     AND RDB$GENERATOR_INCREMENT=1)) THEN
        EXCEPTION PGWIRE_COMPAT.TEMP_CONFIG_ERROR;

    SELECT RDB$VIEW_SOURCE FROM SYSTEM.RDB$RELATIONS
        WHERE RDB$SCHEMA_NAME='pg_catalog' AND RDB$RELATION_NAME='pg_class' INTO :SOURCE_TEXT;
    SOURCE_TEXT = REPLACE(REPLACE(REPLACE(REPLACE(SOURCE_TEXT, ASCII_CHAR(10), ''), ASCII_CHAR(13), ''), ASCII_CHAR(9), ''), ' ', '');
    IF (SOURCE_TEXT IS DISTINCT FROM 'SELECTDISTINCTOID,RELNAME,RELNAMESPACE,RELKINDFROMPG_CATALOG.PG_CLASS') THEN
        EXCEPTION PGWIRE_COMPAT.TEMP_CONFIG_ERROR;
    SOURCE_TEXT = NULL;
    SELECT RDB$VIEW_SOURCE FROM SYSTEM.RDB$RELATIONS
        WHERE RDB$SCHEMA_NAME='pg_catalog' AND RDB$RELATION_NAME='pg_namespace' INTO :SOURCE_TEXT;
    SOURCE_TEXT = REPLACE(REPLACE(REPLACE(REPLACE(SOURCE_TEXT, ASCII_CHAR(10), ''), ASCII_CHAR(13), ''), ASCII_CHAR(9), ''), ' ', '');
    IF (SOURCE_TEXT IS DISTINCT FROM 'SELECTDISTINCTOID,NSPNAMEFROMPG_CATALOG.PG_NAMESPACE') THEN
        EXCEPTION PGWIRE_COMPAT.TEMP_CONFIG_ERROR;
    SOURCE_TEXT = NULL;
    SELECT RDB$FUNCTION_SOURCE FROM SYSTEM.RDB$FUNCTIONS
        WHERE RDB$SCHEMA_NAME='pg_catalog' AND RDB$FUNCTION_NAME='pg_table_is_visible'
          AND RDB$SQL_SECURITY=FALSE INTO :SOURCE_TEXT;
    SOURCE_TEXT = REPLACE(REPLACE(REPLACE(REPLACE(SOURCE_TEXT, ASCII_CHAR(10), ''), ASCII_CHAR(13), ''), ASCII_CHAR(9), ''), ' ', '');
    IF (SOURCE_TEXT IS DISTINCT FROM 'DECLARE"exact_name"VARCHAR(63)CHARACTERSETSYSTEM.UTF8;DECLARE"relation_id"INTEGER;BEGINSELECTC."relname"FROM"pg_catalog"."pg_class"CWHEREC."oid"=:"relation_oid"INTO:"exact_name";IF("exact_name"ISNULL)THENRETURNNULL;"relation_id"=RDB$PG_RELATION_ID("exact_name");RETURNCOALESCE("relation_id"="relation_oid"-1,FALSE);END') THEN
        EXCEPTION PGWIRE_COMPAT.TEMP_CONFIG_ERROR;
    COUNTER_VALUE = GEN_ID(PGWIRE_COMPAT.NAMESPACE_SEQ, 0);
    IF (COUNTER_VALUE < 0 OR COUNTER_VALUE > 4294967295) THEN
        EXCEPTION PGWIRE_COMPAT.TEMP_CONFIG_ERROR;
    -- Persistent relation IDs are 0..32767, public relation IDs are 1..32768.
    -- Sequence increments are native and nontransactional; failed install may leave gaps.
    IF (COUNTER_VALUE < 32768) THEN
        COUNTER_VALUE = GEN_ID(PGWIRE_COMPAT.NAMESPACE_SEQ, 32768 - COUNTER_VALUE);
END^
SET TERM ;^

CREATE SCHEMA PGWIRE_TEMP;
GRANT USAGE ON SCHEMA PGWIRE_TEMP TO PUBLIC;
GRANT CREATE TABLE ON SCHEMA PGWIRE_TEMP TO PUBLIC;
GRANT USAGE ON SEQUENCE PGWIRE_COMPAT.NAMESPACE_SEQ TO PUBLIC;

SET TERM ^;
CREATE TRIGGER PGWIRE_COMPAT.TEMP_CONTAINER_GUARD
    ACTIVE BEFORE ANY DDL STATEMENT
    SQL SECURITY INVOKER
AS
BEGIN
    -- Native created LTT DDL does not invoke database DDL triggers.
    IF (RDB$GET_CONTEXT('DDL_TRIGGER', 'SCHEMA_NAME') = 'PGWIRE_TEMP') THEN
        EXCEPTION PGWIRE_COMPAT.TEMP_CONFIG_ERROR;
END^

CREATE PROCEDURE PGWIRE_COMPAT.TEMP_ROWS_V1
RETURNS (
    ROW_KIND SMALLINT,
    PUBLIC_ID BIGINT,
    NATIVE_ID INTEGER,
    RELATION_NAME VARCHAR(63) CHARACTER SET SYSTEM.UTF8,
    NAMESPACE_ID BIGINT,
    NAMESPACE_NAME VARCHAR(63) CHARACTER SET SYSTEM.UTF8
)
EXTERNAL NAME 'PGWIRE_TEMP_ROWS_V1' ENGINE SYSTEM^
SET TERM ;^

CREATE VIEW PGWIRE_COMPAT.RELATIONS (OID, RELNAME, RELNAMESPACE, RELKIND, NATIVE_ID) AS
    SELECT DISTINCT C.OID, C.RELNAME, C.RELNAMESPACE, C.RELKIND, CAST(C.OID - 1 AS INTEGER)
      FROM PG_CATALOG.PG_CLASS C
    UNION ALL
    SELECT T.PUBLIC_ID, T.RELATION_NAME, T.NAMESPACE_ID,
           CAST('r' AS VARCHAR(1) CHARACTER SET SYSTEM.UTF8), T.NATIVE_ID
      FROM PGWIRE_COMPAT.TEMP_ROWS_V1 T WHERE T.ROW_KIND = 1;

ALTER VIEW "pg_catalog"."pg_class"("oid", "relname", "relnamespace", "relkind") AS
    SELECT DISTINCT OID, RELNAME, RELNAMESPACE, RELKIND FROM PGWIRE_COMPAT.RELATIONS;

ALTER VIEW "pg_catalog"."pg_namespace"("oid", "nspname") AS
    SELECT DISTINCT OID, NSPNAME FROM PG_CATALOG.PG_NAMESPACE WHERE NSPNAME <> 'PGWIRE_TEMP'
    UNION ALL
    SELECT PUBLIC_ID, NAMESPACE_NAME FROM PGWIRE_COMPAT.TEMP_ROWS_V1 WHERE ROW_KIND = 0;

SET TERM ^;
CREATE FUNCTION "pg_catalog"."pg_my_temp_schema" RETURNS BIGINT
SQL SECURITY INVOKER
AS
BEGIN
    RETURN COALESCE((SELECT PUBLIC_ID FROM PGWIRE_COMPAT.TEMP_ROWS_V1 WHERE ROW_KIND = 0), 0);
END^

ALTER FUNCTION "pg_catalog"."pg_table_is_visible"("relation_oid" BIGINT)
RETURNS BOOLEAN
SQL SECURITY INVOKER
AS
DECLARE "exact_name" VARCHAR(63) CHARACTER SET SYSTEM.UTF8;
DECLARE "expected_id" INTEGER;
BEGIN
    SELECT RELNAME, NATIVE_ID FROM PGWIRE_COMPAT.RELATIONS
        WHERE OID = :"relation_oid" INTO :"exact_name", :"expected_id";
    IF ("exact_name" IS NULL) THEN
        RETURN NULL;
    RETURN COALESCE(RDB$PG_RELATION_ID("exact_name") = "expected_id", FALSE);
END^
SET TERM ;^

GRANT EXECUTE ON PROCEDURE PGWIRE_COMPAT.TEMP_ROWS_V1 TO PUBLIC;
GRANT SELECT ON PGWIRE_COMPAT.RELATIONS TO PUBLIC;
GRANT EXECUTE ON FUNCTION "pg_catalog"."pg_my_temp_schema" TO PUBLIC;
-- ALTER VIEW/FUNCTION preserve the existing grants and persistent identities.
COMMIT;
