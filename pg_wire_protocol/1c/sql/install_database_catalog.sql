-- Current-database catalog projection; no enumeration of server databases.
-- Requires APP-16, installed once as database owner, without concurrent DDL.
-- Identity and locale come from native metadata, not the PgWire startup string.
SET BAIL ON;
SET AUTODDL OFF;

CREATE EXCEPTION PGWIRE_COMPAT.DATABASE_PROFILE_ERROR
    'PgWire database catalog requires APP-16, UTF8 and a supported default collation';
SET TERM ^;
EXECUTE BLOCK AS
BEGIN
    IF (NOT EXISTS (SELECT 1 FROM SYSTEM.RDB$FUNCTIONS
                    WHERE RDB$SCHEMA_NAME = 'public' AND RDB$FUNCTION_NAME = 'binrowver') OR
        NOT EXISTS (SELECT 1 FROM SYSTEM.RDB$FUNCTIONS
                    WHERE RDB$SCHEMA_NAME = 'public' AND RDB$FUNCTION_NAME = 'bool_or')) THEN
        EXCEPTION PGWIRE_COMPAT.DATABASE_PROFILE_ERROR;
END^

CREATE FUNCTION "pg_catalog"."current_database" RETURNS VARCHAR(1024) CHARACTER SET UTF8
SQL SECURITY INVOKER
AS
BEGIN
    RETURN RDB$GET_CONTEXT('SYSTEM', 'DB_NAME');
END^

CREATE FUNCTION PGWIRE_COMPAT.DATABASE_COLLATION RETURNS VARCHAR(32) CHARACTER SET UTF8
SQL SECURITY INVOKER
AS
DECLARE COLLATION_SCHEMA VARCHAR(63) CHARACTER SET UTF8;
DECLARE COLLATION_NAME VARCHAR(63) CHARACTER SET UTF8;
DECLARE BASE_NAME VARCHAR(63) CHARACTER SET UTF8;
DECLARE ATTRIBUTES SMALLINT;
DECLARE SPECIFIC_ATTRIBUTES VARCHAR(1024) CHARACTER SET UTF8;
BEGIN
    SELECT C.RDB$SCHEMA_NAME, C.RDB$COLLATION_NAME, C.RDB$BASE_COLLATION_NAME,
           C.RDB$COLLATION_ATTRIBUTES, C.RDB$SPECIFIC_ATTRIBUTES
      FROM SYSTEM.RDB$DATABASE D
      JOIN SYSTEM.RDB$CHARACTER_SETS S ON S.RDB$CHARACTER_SET_NAME = D.RDB$CHARACTER_SET_NAME
      JOIN SYSTEM.RDB$COLLATIONS C ON C.RDB$SCHEMA_NAME = S.RDB$DEFAULT_COLLATE_SCHEMA_NAME
                                 AND C.RDB$COLLATION_NAME = S.RDB$DEFAULT_COLLATE_NAME
                                 AND C.RDB$CHARACTER_SET_ID = S.RDB$CHARACTER_SET_ID
     WHERE S.RDB$SCHEMA_NAME = 'SYSTEM' AND S.RDB$CHARACTER_SET_NAME = 'UTF8'
      INTO COLLATION_SCHEMA, COLLATION_NAME, BASE_NAME, ATTRIBUTES, SPECIFIC_ATTRIBUTES;
    IF (COLLATION_SCHEMA = 'SYSTEM' AND COLLATION_NAME = 'UTF8' AND ATTRIBUTES = 1) THEN
        RETURN 'C.UTF-8';
    IF (COLLATION_SCHEMA = 'PGWIRE_COMPAT' AND COLLATION_NAME = 'RU_RU_UTF8' AND
        BASE_NAME = 'UNICODE' AND ATTRIBUTES = 1 AND
        POSITION(';LOCALE=ru_RU;' IN ';' || SPECIFIC_ATTRIBUTES || ';') > 0) THEN
        RETURN 'ru_RU.UTF-8';
    EXCEPTION PGWIRE_COMPAT.DATABASE_PROFILE_ERROR;
END^
SET TERM ;^

CREATE VIEW "pg_catalog"."pg_database"("datname", "datcollate") AS
    SELECT DISTINCT "pg_catalog"."current_database"(), PGWIRE_COMPAT.DATABASE_COLLATION()
      FROM SYSTEM.RDB$DATABASE;

-- Firebird has no PostgreSQL named tablespaces. This is their actual empty
-- namespace, including absence of application v81c_data/v81c_index locations.
CREATE VIEW "pg_catalog"."pg_tablespace"("spcname") AS
    SELECT DISTINCT CAST(NULL AS VARCHAR(63) CHARACTER SET UTF8)
      FROM SYSTEM.RDB$DATABASE WHERE FALSE;

GRANT EXECUTE ON FUNCTION "pg_catalog"."current_database" TO PUBLIC;
GRANT EXECUTE ON FUNCTION PGWIRE_COMPAT.DATABASE_COLLATION TO PUBLIC;
GRANT USAGE ON EXCEPTION PGWIRE_COMPAT.DATABASE_PROFILE_ERROR TO PUBLIC;
GRANT SELECT ON "pg_catalog"."pg_database" TO PUBLIC;
GRANT SELECT ON "pg_catalog"."pg_tablespace" TO PUBLIC;

-- Validate before committing any object. Later unsupported native changes must
-- also fail when queried instead of returning an obsolete installed constant.
SELECT PGWIRE_COMPAT.DATABASE_COLLATION() FROM SYSTEM.RDB$DATABASE;
COMMIT;
