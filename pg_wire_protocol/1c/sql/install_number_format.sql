-- Native PSQL equivalent of the captured 1C format_number function.
-- VARCHAR input preserves exact native NUMERIC(p,s) scale and up to 38 digits.
-- It also makes the limited parameter contract explicit: direct numeric Bind
-- requires CAST($n AS NUMERIC(p,s)); no variable-scale numeric type is invented.
SET BAIL ON;
SET AUTODDL OFF;
CREATE EXCEPTION PGWIRE_COMPAT.NUMBER_FORMAT_INPUT_ERROR
    'format_number requires a finite decimal representation without an exponent';
SET TERM ^;
CREATE FUNCTION "public"."format_number"(
    NUM VARCHAR(8191) CHARACTER SET UTF8 COLLATE SYSTEM.UTF8,
    GRPLEN INTEGER, SECGRPLEN INTEGER,
    GRPSEP VARCHAR(8191) CHARACTER SET UTF8,
    DECSEP VARCHAR(8191) CHARACTER SET UTF8)
RETURNS VARCHAR(8191) CHARACTER SET UTF8
SQL SECURITY INVOKER
AS
DECLARE NUMSTR VARCHAR(8191) CHARACTER SET UTF8;
DECLARE OUTSTR VARCHAR(8191) CHARACTER SET UTF8;
DECLARE SIGN_PREFIX CHAR(1) CHARACTER SET UTF8;
DECLARE INTEGER_PART VARCHAR(8191) CHARACTER SET UTF8;
DECLARE DOTPOS INTEGER;
DECLARE NUMSTRLEN INTEGER;
DECLARE STARTPOS INTEGER;
DECLARE CURPOS INTEGER;
BEGIN
    IF (NUM IS NULL) THEN RETURN NULL;
    NUMSTR = TRIM(NUM);
    SIGN_PREFIX = '';
    IF (LEFT(NUMSTR, 1) IN ('+', '-')) THEN
    BEGIN
        IF (LEFT(NUMSTR, 1) = '-') THEN SIGN_PREFIX = '-';
        NUMSTR = SUBSTRING(NUMSTR FROM 2);
    END
    IF (NOT (NUMSTR SIMILAR TO '([0-9]+([.][0-9]*)?|[.][0-9]+)')) THEN
        EXCEPTION PGWIRE_COMPAT.NUMBER_FORMAT_INPUT_ERROR;
    -- Match the canonical finite decimal spelling supplied by a PG numeric.
    DOTPOS = POSITION('.' IN NUMSTR);
    INTEGER_PART = TRIM(LEADING '0' FROM
        CASE WHEN DOTPOS = 0 THEN NUMSTR ELSE LEFT(NUMSTR, DOTPOS - 1) END);
    IF (INTEGER_PART = '') THEN INTEGER_PART = '0';
    IF (DOTPOS = 0 OR DOTPOS = CHAR_LENGTH(NUMSTR)) THEN NUMSTR = INTEGER_PART;
    ELSE NUMSTR = INTEGER_PART || SUBSTRING(NUMSTR FROM DOTPOS);
    IF (REPLACE(REPLACE(NUMSTR, '0', ''), '.', '') <> '') THEN
        NUMSTR = TRIM(SIGN_PREFIX) || NUMSTR;

    DOTPOS = POSITION('.' IN NUMSTR);
    IF (DOTPOS > 0) THEN
    BEGIN
        -- Source RTRIM(text, '0.') treats its second argument as a character
        -- set: 100.00 -> '1', while integer 100 -> '100'; 0.00 -> ''.
        WHILE (CHAR_LENGTH(NUMSTR) > 0 AND RIGHT(NUMSTR, 1) IN ('0', '.')) DO
            NUMSTR = LEFT(NUMSTR, CHAR_LENGTH(NUMSTR) - 1);
        DOTPOS = POSITION('.' IN NUMSTR);
    END
    NUMSTRLEN = CHAR_LENGTH(NUMSTR);
    IF (GRPLEN > 0 AND GRPLEN < NUMSTRLEN) THEN
    BEGIN
        OUTSTR = CASE WHEN DOTPOS = 0 THEN ''
            ELSE DECSEP || RIGHT(NUMSTR, NUMSTRLEN - DOTPOS) END;
        IF (DOTPOS = 0) THEN DOTPOS = NUMSTRLEN + 1;
        STARTPOS = CASE WHEN LEFT(NUMSTR, 1) = '-' THEN 2 ELSE 1 END;
        CURPOS = DOTPOS;
        WHILE (CURPOS > 0) DO
        BEGIN
            OUTSTR = SUBSTRING(NUMSTR FROM CURPOS - GRPLEN FOR GRPLEN) ||
                CASE WHEN CURPOS < DOTPOS AND CURPOS > STARTPOS THEN GRPSEP ELSE '' END || OUTSTR;
            CURPOS = CURPOS - GRPLEN;
            IF (SECGRPLEN > 0 AND SECGRPLEN < NUMSTRLEN) THEN GRPLEN = SECGRPLEN;
        END
        RETURN OUTSTR;
    END
    -- Native VARCHAR equality pads spaces; PG's decsep <> '.' does not.
    IF ((CHAR_LENGTH(DECSEP) <> 1 OR DECSEP <> '.') AND DOTPOS > 0) THEN
        RETURN REPLACE(NUMSTR, '.', DECSEP);
    RETURN NUMSTR;
END^
SET TERM ;^
GRANT EXECUTE ON FUNCTION "public"."format_number" TO PUBLIC;
GRANT USAGE ON EXCEPTION PGWIRE_COMPAT.NUMBER_FORMAT_INPUT_ERROR TO PUBLIC;
COMMIT;
