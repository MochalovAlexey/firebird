-- Native implementations of application functions required by 1C bootstrap.
-- Install once after the compatibility schemas, as database owner.
SET BAIL ON;
SET AUTODDL OFF;

CREATE EXCEPTION PGWIRE_COMPAT.DATEDIFF2_MODE_ERROR
    'datediff2 requires SECOND, MINUTE, HOUR, DAY, WEEK, MONTH, QUARTER or YEAR';
SET TERM ^;
CREATE FUNCTION "public"."datediff2"(
    ARG_MODE VARCHAR(8191) CHARACTER SET UTF8 COLLATE SYSTEM.UTF8,
    ARG_D2 TIMESTAMP, ARG_D1 TIMESTAMP)
RETURNS INTEGER
SQL SECURITY INVOKER
AS
DECLARE MODE_LENGTH INTEGER;
DECLARE ELAPSED DOUBLE PRECISION;
DECLARE WHOLE BIGINT;
DECLARE FRACTION DOUBLE PRECISION;
BEGIN
    MODE_LENGTH = OCTET_LENGTH(ARG_MODE);
    -- VARCHAR comparison in PostgreSQL preserves trailing spaces. The explicit
    -- binary collation and length also isolate modes from the database locale.
    IF ((MODE_LENGTH = 6 AND ARG_MODE IN ('SECOND', 'MINUTE')) OR
        (MODE_LENGTH = 4 AND ARG_MODE = 'HOUR')) THEN
    BEGIN
        -- Match the source function's two float8 epoch values, including their
        -- subtraction rounding. Native timestamps have 100-microsecond ticks.
        ELAPSED =
            CAST(CAST(DATEDIFF(MILLISECOND FROM TIMESTAMP '1970-01-01' TO ARG_D1) * 1000
                      AS BIGINT) AS DOUBLE PRECISION) / 1000000 -
            CAST(CAST(DATEDIFF(MILLISECOND FROM TIMESTAMP '1970-01-01' TO ARG_D2) * 1000
                      AS BIGINT) AS DOUBLE PRECISION) / 1000000;
        IF (ARG_MODE = 'MINUTE') THEN RETURN TRUNC(ELAPSED / 60);
        IF (ARG_MODE = 'HOUR') THEN RETURN TRUNC(ELAPSED / 3600);
        -- PostgreSQL float8 -> int4 uses nearest/even, unlike a native cast.
        WHOLE = TRUNC(ELAPSED);
        FRACTION = ABS(ELAPSED - WHOLE);
        IF (FRACTION > 0.5 OR (FRACTION = 0.5 AND MOD(WHOLE, 2) <> 0)) THEN
            WHOLE = WHOLE + SIGN(ELAPSED);
        RETURN WHOLE;
    END
    IF (MODE_LENGTH = 3 AND ARG_MODE = 'DAY') THEN
        RETURN DATEDIFF(DAY FROM ARG_D2 TO ARG_D1);
    IF (MODE_LENGTH = 4 AND ARG_MODE = 'WEEK') THEN
        RETURN DATEDIFF(WEEK FROM ARG_D2 TO ARG_D1);
    IF (MODE_LENGTH = 5 AND ARG_MODE = 'MONTH') THEN
        RETURN DATEDIFF(MONTH FROM ARG_D2 TO ARG_D1);
    IF (MODE_LENGTH = 7 AND ARG_MODE = 'QUARTER') THEN
        RETURN 4 * DATEDIFF(YEAR FROM ARG_D2 TO ARG_D1) +
            EXTRACT(QUARTER FROM ARG_D1) - EXTRACT(QUARTER FROM ARG_D2);
    IF (MODE_LENGTH = 4 AND ARG_MODE = 'YEAR') THEN
        RETURN DATEDIFF(YEAR FROM ARG_D2 TO ARG_D1);
    EXCEPTION PGWIRE_COMPAT.DATEDIFF2_MODE_ERROR;
END^

CREATE FUNCTION "public"."vassn"(BEXPR BOOLEAN)
RETURNS INTEGER
SQL SECURITY INVOKER
AS
BEGIN
    RETURN IIF(BEXPR, 0, 2000000000);
END^
SET TERM ;^
GRANT EXECUTE ON FUNCTION "public"."datediff2" TO PUBLIC;
GRANT EXECUTE ON FUNCTION "public"."vassn" TO PUBLIC;
GRANT USAGE ON EXCEPTION PGWIRE_COMPAT.DATEDIFF2_MODE_ERROR TO PUBLIC;
COMMIT;
