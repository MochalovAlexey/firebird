#!/usr/bin/env python3
"""Native local identity and PG serial4 acceptance in a private runtime."""
import argparse
import hashlib
import json
from pathlib import Path
import subprocess
import sys

from pgwire_1c_smoke import Libpq
from pgwire_namespace_checks import config_for, native, numbers
from pgwire_startup_smoke import Client, StartupHarness
from wire_host_smoke import require, reserve_ports

PROFILE = Path(__file__).resolve().parents[1] / '1c'


def run(h, capture):
    h.prepare()
    h.isql('serial_admin', f"CONNECT '{h.database}';\n"
           f"CREATE OR ALTER USER SYSDBA PASSWORD '{h.password}';\nCOMMIT;\nQUIT;\n", embedded=True)
    result = subprocess.run([sys.executable, '-B', str(PROFILE / 'install_compat.py'), '--isql',
                            str(h.runtime / 'bin/isql'), '-d', str(h.database)],
                            env=h.env, cwd=h.temp, capture_output=True, text=True, timeout=h.timeout)
    (h.work / 'install.log').write_text(h.redact(result.stdout + result.stderr))
    require(result.returncode == 0, 'Compatibility installation failed')
    config = config_for(h)
    native(config, 'serial_grants', 'GRANT CREATE TABLE ON SCHEMA "public" TO USER WIRE_HOST_TEST;\n'
           'GRANT CREATE TABLE ON SCHEMA PUBLIC TO USER WIRE_HOST_TEST;\nCOMMIT;', admin=True)
    out = native(config, 'native_identity', '''
CREATE LOCAL TEMPORARY TABLE native_identity(id INTEGER GENERATED BY DEFAULT AS IDENTITY
  (START WITH 10 INCREMENT BY 5), v INTEGER) ON COMMIT PRESERVE ROWS;
COMMIT;
INSERT INTO native_identity(v) VALUES(1) RETURNING id AS N;
SAVEPOINT a;
INSERT INTO native_identity(v) VALUES(2) RETURNING id AS N;
ROLLBACK TO a;
INSERT INTO native_identity(v) VALUES(3) RETURNING id AS N;
COMMIT;
SELECT id AS N FROM native_identity ORDER BY id;
ROLLBACK;
''')['output']
    require(numbers(out) == [10, 15, 20, 10, 20], 'Native LTT identity/rollback differs')
    out = native(config, 'native_always', '''
CREATE LOCAL TEMPORARY TABLE always_identity(id INTEGER GENERATED ALWAYS AS IDENTITY)
  ON COMMIT PRESERVE ROWS;
COMMIT;
INSERT INTO always_identity DEFAULT VALUES RETURNING id AS N;
INSERT INTO always_identity VALUES(99);
''', error=True)['output']
    require(numbers(out) == [1], 'Native ALWAYS identity accepted an explicit value')
    out = native(config, 'native_counter_overflow', '''
CREATE LOCAL TEMPORARY TABLE limit_identity(id BIGINT GENERATED BY DEFAULT AS IDENTITY
  (START WITH 9223372036854775807)) ON COMMIT PRESERVE ROWS;
COMMIT;
INSERT INTO limit_identity DEFAULT VALUES RETURNING id AS N;
INSERT INTO limit_identity DEFAULT VALUES;
''', error=True)['output']
    require(numbers(out) == [9223372036854775807], 'Native counter overflow wrapped or failed early')
    native(config, 'native_serial_not_type', 'CREATE LOCAL TEMPORARY TABLE bad_native(i serial4);', error=True)
    native_port, pg_port = reserve_ports(2)
    h.start('serial', native_port, native_port, [{'alias': 'PgWire', 'port': pg_port}])
    ready = Client(h)
    try:
        ready.login()
        ready.query_integer()
    finally:
        ready.close()
    config = dict(config_for(h), port=pg_port)
    first, second = Libpq(config), Libpq(config)
    checks = []
    try:
        def query(label, sql, rows=None, error=False, client=first):
            response = client.query(sql, True)
            result = response[-1]
            checks.append({'label': label, 'results': response})
            (h.work / 'progress.json').write_text(json.dumps(checks, indent=2) + '\n')
            require(bool(result['sqlstate']) == error and
                    (error or all(not part['sqlstate'] for part in response)) and
                    (rows is None or result['rows'] == rows), f'{label}: {response}')
            return result

        query('create', 'CREATE TEMP TABLE serial_rows(id serial4, v integer)')
        prepared = first.result(first.pq.PQprepare(first.connection, b'identity_insert',
                                b'INSERT INTO serial_rows(v) VALUES($1) RETURNING id', 0, None))
        require(not prepared['sqlstate'], f'Identity Prepare failed: {prepared}')
        query('first_default', 'INSERT INTO serial_rows(v) VALUES(10) RETURNING id', [['1']])
        query('explicit_value', 'INSERT INTO serial_rows VALUES(70,70) RETURNING id', [['70']])
        query('explicit_null', 'INSERT INTO serial_rows VALUES(NULL,99)', error=True)
        query('null_did_not_advance', 'INSERT INTO serial_rows(v) VALUES(20) RETURNING id', [['2']])
        query('default_keyword', 'INSERT INTO serial_rows VALUES(DEFAULT,30) RETURNING id', [['3']])
        query('begin', 'BEGIN')
        query('before_savepoint', 'INSERT INTO serial_rows(v) VALUES(40) RETURNING id', [['4']])
        query('savepoint', 'SAVEPOINT s')
        query('after_savepoint', 'INSERT INTO serial_rows(v) VALUES(50) RETURNING id', [['5']])
        query('rollback_savepoint', 'ROLLBACK TO s')
        query('sequence_not_undone', 'INSERT INTO serial_rows(v) VALUES(60) RETURNING id', [['6']])
        query('rollback', 'ROLLBACK')
        query('transaction_not_undone', 'INSERT INTO serial_rows(v) VALUES(80) RETURNING id', [['7']])
        query('second_attachment', 'CREATE TEMP TABLE serial_rows(id serial4, v integer)', client=second)
        query('independent_identity', 'INSERT INTO serial_rows(v) VALUES(10) RETURNING id', [['1']], client=second)
        query('begin_ddl', 'BEGIN')
        query('savepoint_ddl', 'SAVEPOINT d')
        query('rename', 'ALTER TABLE serial_rows ALTER id TO new_id')
        query('renamed_identity', 'INSERT INTO serial_rows(v) VALUES(90) RETURNING new_id', [['8']])
        query('undo_rename', 'ROLLBACK TO d')
        query('metadata_undo_not_counter_undo', 'INSERT INTO serial_rows(v) VALUES(100) RETURNING id', [['9']])
        query('drop', 'DROP TABLE serial_rows')
        query('undo_drop', 'ROLLBACK TO d')
        query('drop_undo_counter', 'INSERT INTO serial_rows(v) VALUES(110) RETURNING id', [['10']])
        query('end_ddl', 'COMMIT')
        query('not_null_preserved', 'ALTER TABLE serial_rows ALTER id DROP NOT NULL', error=True)
        query('invalid_identity_type', 'ALTER TABLE serial_rows ALTER id TYPE VARCHAR(20)', error=True)
        query('unsupported_alter_add', 'ALTER TABLE serial_rows ADD another serial4', error=True)
        result = first.params('identity_insert', ['120'], prepared=True)
        require(result['rows'] == [['11']] and result['columns'][0]['oid'] == 23, f'Extended identity differs: {result}')
        query('drop_recreate', 'DROP TABLE serial_rows; CREATE TEMP TABLE serial_rows(id serial4, v integer)')
        query('new_counter', 'INSERT INTO serial_rows(v) VALUES(1) RETURNING id', [['1']])
        result = first.params('identity_insert', ['130'], prepared=True)
        require(result['rows'] == [['2']], f'Prepared identity did not bind to the recreated table: {result}')
        query('move_identity_position', 'ALTER TABLE serial_rows ALTER id POSITION 2')
        query('identity_after_position', 'INSERT INTO serial_rows(v) VALUES(140) RETURNING id', [['3']])
        query('two_identities', 'CREATE TEMP TABLE pair_identity(a serial4, b serial4)')
        query('independent_columns', 'INSERT INTO pair_identity DEFAULT VALUES RETURNING a,b', [['1', '1']])
        query('independent_explicit_column', 'INSERT INTO pair_identity(a) VALUES(9) RETURNING a,b', [['9', '2']])
        query('drop_nonlast_identity', 'ALTER TABLE pair_identity DROP a')
        query('surviving_identity', 'INSERT INTO pair_identity DEFAULT VALUES RETURNING b', [['3']])
        query('old_formats_after_drop', 'SELECT b FROM pair_identity ORDER BY b', [['1'], ['2'], ['3']])
        query('error_counter_fixture', 'CREATE TEMP TABLE error_identity(id serial4, v integer NOT NULL)')
        query('failed_insert', 'INSERT INTO error_identity(v) VALUES(NULL)', error=True)
        query('failed_insert_consumed_value', 'INSERT INTO error_identity(v) VALUES(1) RETURNING id', [['2']])
        query('persistent_serial', 'CREATE TABLE serial_persistent(id serial, v integer)')
        query('persistent_default', 'INSERT INTO serial_persistent(v) VALUES(1) RETURNING id', [['1']])
        query('persistent_null', 'INSERT INTO serial_persistent VALUES(NULL,2)', error=True)
        query('persistent_native', 'SELECT id FROM serial_persistent', [['1']], client=second)
        query('serial_not_cast_type', 'SELECT 1::serial4', error=True)
        query('serial_default_conflict', 'CREATE TEMP TABLE bad_serial(id serial4 DEFAULT 4)', error=True)
        if capture:
            sql = (capture / 'profile/selected/13-temporary-serial.sql').read_bytes()
            query('captured_13', sql)
            query('captured_13_generated', 'INSERT INTO tt1(_C_9) VALUES(1) RETURNING SDBL_IDENTITY', [['1']])
            h.summary['captured_sql_sha256'] = hashlib.sha256(sql).hexdigest()
        h.summary.update(serial_cases=checks, native_ltt_identity=True, nontransactional_values=True,
                         independent_attachments=True, metadata_undo_preserves_values=True)
    finally:
        first.close()
        second.close()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--firebird-dir', type=Path, required=True)
    parser.add_argument('--work-dir', type=Path, required=True)
    parser.add_argument('--capture-dir', type=Path)
    args = parser.parse_args()
    args.work_dir.mkdir(mode=0o700, parents=True, exist_ok=False)
    h = StartupHarness(args.firebird_dir.resolve(), args.work_dir.resolve(), 120)
    h.summary['stage'] = 'Native LTT identity and PG serial4'
    try:
        run(h, args.capture_dir)
        h.close()
        h.summary['passed'] = True
    finally:
        h.close()
        if h.trap:
            h.trap.close()
        (h.work / 'summary.json').write_text(json.dumps(h.summary, ensure_ascii=False, indent=2) + '\n')
    print(h.work / 'summary.json')


if __name__ == '__main__':
    main()
