-- Native dialect 3 regression: EXISTS/NOT EXISTS with no source-dependent join conjuncts.
-- Run with this fork's isql against a disposable database. No PgWire setup is required.
-- A failed check raises an exception; SET BAIL ON stops the script. Successful execution
-- removes its fixture objects. This script never belongs in the compatibility installer.
SET BAIL ON;
SET AUTODDL OFF;
SET SQL DIALECT 3;
CREATE TABLE PGWIRE_SEMI_TARGET(ID INTEGER, V INTEGER);
CREATE TABLE PGWIRE_SEMI_SOURCE(ID INTEGER, PAYLOAD INTEGER);
CREATE EXCEPTION PGWIRE_SEMI_FAILED 'Unexpected remaining rows after native semijoin';
SET TERM ^;
CREATE PROCEDURE PGWIRE_SEMI_CHECK(EXPECTED_COUNT INTEGER, EXPECTED_MASK INTEGER)
AS
DECLARE ACTUAL_COUNT INTEGER;
DECLARE ACTUAL_MASK INTEGER;
BEGIN
    SELECT COUNT(*), COALESCE(SUM(CASE ID
        WHEN 1 THEN 1 WHEN 2 THEN 2 WHEN 3 THEN 4
        ELSE IIF(ID IS NULL, 8, 16) END), 0)
    FROM PGWIRE_SEMI_TARGET INTO ACTUAL_COUNT, ACTUAL_MASK;
    IF (ACTUAL_COUNT <> EXPECTED_COUNT OR ACTUAL_MASK <> EXPECTED_MASK) THEN
        EXCEPTION PGWIRE_SEMI_FAILED;
END^
SET TERM ;^;
COMMIT;
INSERT INTO PGWIRE_SEMI_TARGET VALUES(1,10);
INSERT INTO PGWIRE_SEMI_TARGET VALUES(2,20);
INSERT INTO PGWIRE_SEMI_TARGET VALUES(3,NULL);
INSERT INTO PGWIRE_SEMI_TARGET VALUES(NULL,40);
INSERT INTO PGWIRE_SEMI_SOURCE VALUES(1,10);
INSERT INTO PGWIRE_SEMI_SOURCE VALUES(1,11);
INSERT INTO PGWIRE_SEMI_SOURCE VALUES(NULL,12);
COMMIT;
SET PLAN ON;

-- target_only
DELETE FROM PGWIRE_SEMI_TARGET T WHERE EXISTS(SELECT 1 FROM PGWIRE_SEMI_SOURCE S WHERE T.V=20) RETURNING T.ID;
EXECUTE PROCEDURE PGWIRE_SEMI_CHECK(3, 13);
ROLLBACK;

-- target_only_no_returning
DELETE FROM PGWIRE_SEMI_TARGET T WHERE EXISTS(SELECT 1 FROM PGWIRE_SEMI_SOURCE S WHERE T.V=20);
EXECUTE PROCEDURE PGWIRE_SEMI_CHECK(3, 13);
ROLLBACK;

-- target_no_match
DELETE FROM PGWIRE_SEMI_TARGET T WHERE EXISTS(SELECT 1 FROM PGWIRE_SEMI_SOURCE S WHERE T.V=99) RETURNING T.ID;
EXECUTE PROCEDURE PGWIRE_SEMI_CHECK(4, 15);
ROLLBACK;

-- target_null
DELETE FROM PGWIRE_SEMI_TARGET T WHERE EXISTS(SELECT 1 FROM PGWIRE_SEMI_SOURCE S WHERE T.V IS NULL) RETURNING T.ID;
EXECUTE PROCEDURE PGWIRE_SEMI_CHECK(3, 11);
ROLLBACK;

-- null_comparison
DELETE FROM PGWIRE_SEMI_TARGET T WHERE EXISTS(SELECT 1 FROM PGWIRE_SEMI_SOURCE S WHERE T.V=NULL) RETURNING T.ID;
EXECUTE PROCEDURE PGWIRE_SEMI_CHECK(4, 15);
ROLLBACK;

-- empty_source
DELETE FROM PGWIRE_SEMI_SOURCE;
DELETE FROM PGWIRE_SEMI_TARGET T WHERE EXISTS(SELECT 1 FROM PGWIRE_SEMI_SOURCE S WHERE T.V=20) RETURNING T.ID;
EXECUTE PROCEDURE PGWIRE_SEMI_CHECK(4, 15);
ROLLBACK;

-- source_only
DELETE FROM PGWIRE_SEMI_TARGET T WHERE EXISTS(SELECT 1 FROM PGWIRE_SEMI_SOURCE S WHERE S.PAYLOAD=10) RETURNING T.ID;
EXECUTE PROCEDURE PGWIRE_SEMI_CHECK(0, 0);
ROLLBACK;

-- source_no_match
DELETE FROM PGWIRE_SEMI_TARGET T WHERE EXISTS(SELECT 1 FROM PGWIRE_SEMI_SOURCE S WHERE S.PAYLOAD=999) RETURNING T.ID;
EXECUTE PROCEDURE PGWIRE_SEMI_CHECK(4, 15);
ROLLBACK;

-- constant_true
DELETE FROM PGWIRE_SEMI_TARGET T WHERE EXISTS(SELECT 1 FROM PGWIRE_SEMI_SOURCE S WHERE TRUE) RETURNING T.ID;
EXECUTE PROCEDURE PGWIRE_SEMI_CHECK(0, 0);
ROLLBACK;

-- correlated_both
DELETE FROM PGWIRE_SEMI_TARGET T WHERE EXISTS(SELECT 1 FROM PGWIRE_SEMI_SOURCE S WHERE T.ID=S.ID) RETURNING T.ID;
EXECUTE PROCEDURE PGWIRE_SEMI_CHECK(3, 14);
ROLLBACK;

-- target_and_source
DELETE FROM PGWIRE_SEMI_TARGET T WHERE EXISTS(SELECT 1 FROM PGWIRE_SEMI_SOURCE S WHERE T.V=20 AND S.PAYLOAD=10) RETURNING T.ID;
EXECUTE PROCEDURE PGWIRE_SEMI_CHECK(3, 13);
ROLLBACK;

-- anti_target_only
DELETE FROM PGWIRE_SEMI_TARGET T WHERE NOT EXISTS(SELECT 1 FROM PGWIRE_SEMI_SOURCE S WHERE T.V=20) RETURNING T.ID;
EXECUTE PROCEDURE PGWIRE_SEMI_CHECK(1, 2);
ROLLBACK;

-- anti_empty_source
DELETE FROM PGWIRE_SEMI_SOURCE;
DELETE FROM PGWIRE_SEMI_TARGET T WHERE NOT EXISTS(SELECT 1 FROM PGWIRE_SEMI_SOURCE S WHERE T.V=20) RETURNING T.ID;
EXECUTE PROCEDURE PGWIRE_SEMI_CHECK(0, 0);
ROLLBACK;

-- anti_correlated
DELETE FROM PGWIRE_SEMI_TARGET T WHERE NOT EXISTS(SELECT 1 FROM PGWIRE_SEMI_SOURCE S WHERE T.ID=S.ID) RETURNING T.ID;
EXECUTE PROCEDURE PGWIRE_SEMI_CHECK(1, 1);
ROLLBACK;

SET PLAN OFF;
DROP PROCEDURE PGWIRE_SEMI_CHECK;
DROP EXCEPTION PGWIRE_SEMI_FAILED;
DROP TABLE PGWIRE_SEMI_SOURCE;
DROP TABLE PGWIRE_SEMI_TARGET;
COMMIT;
SELECT '14 native EXISTS/NOT EXISTS checks passed' AS RESULT FROM SYSTEM.RDB$DATABASE;
